// 跑一段剧本到她去为止。返回定档那一刻的电荷（不是事后剩下的——去了要卸，
// 事后读到的是残值，拿它对照会得出反过来的结论）。
function 跑剧本(剧本, 造人参数 = { stage: '孕晚期', days: 252 }, 起始值 = null) {
  const cs = 造人(造人参数);
  if (起始值 !== null) p(cs).metabolism.libido = 起始值;
  let 结果 = '';
  let 定档 = 0;
  const 轨迹 = [];
  for (const [动作, 档, 分] of 剧本) {
    定档 = 电荷(cs);
    const r = 档 === 0 ? 停(cs, 分) : 做(cs, 档, 分);
    轨迹.push(`${动作}(闸${闸(cs).toFixed(0)}/电荷${电荷(cs).toFixed(0)})`);
    if (r) { 结果 = r; break; }
  }
  return { cs, 结果, 定档, 轨迹 };
}

