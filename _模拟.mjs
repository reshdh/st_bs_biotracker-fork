// ── 造人 ────────────────────────────────────────────────────────────
// days 是有效孕龄天数；engaged=true 表示胎头已入盆。不给 stage 就是非孕期。
function 造人({ stage = '黄体期', days = 0, engaged = false } = {}) {
  const 孕 = ['孕早期', '孕中期', '孕晚期', '临产期', '逾期'].includes(stage);
  const chatState = state.createEmptyChatState();
  chatState.characters['她'] = {
    name: '她', initialized: true, runtime: {},
    profile: {
      base: {
        stage, days: 3, vitality: 100, psyStress: 30, uterinePressure: 0,
        age: 24, race: '人类', eggs: 0, vitalityLevel: 4, psyStressLevel: 4,
      },
      pregnant: {
        pregnantDays: days, effectivePregnantDays: days,
        fetusesCount: 孕 ? 1 : 0,
        fetuses: 孕 ? [{ descent: engaged ? 60 : 10, weight: 1.2, tendencyAngle: 0 }] : [],
        fetalEnergyDrain: 0, amnionDurability: 50,
      },
      bio: { birthDifficulty: 1, breedTolerance: 1, orgasmOvulationAmount: 1, milkGate: '中' },
      immune: {},
      metabolism: { urine: 0, stool: 0, hunger: 0, sleep: 0, milk: 0, odor: 0, companionship: 0, libido: 0 },
      libido: {},
      experience: {}, children: [], notify: {}, cooldown: {},
    },
  };
  // 从起点出发——实际游戏里她坐在起点上，不是 0
  const L = getLibidoLines(stage, days, engaged ? 1 : 0, 孕);
  chatState.characters['她'].profile.metabolism.libido = L.floor;
  return chatState;
}

const p = (cs) => cs.characters['她'].profile;
const 值 = (cs) => Number(p(cs).metabolism.libido) || 0;
const 闸 = (cs) => Number(p(cs).libido?.gate) || 0;
const 电荷 = (cs) => Number(p(cs).libido?.charge) || 0;

// 报一档刺激。档位：0无 1想象 2环境 3轻 4中 5重
function 做(cs, 档, 分钟, 本轮分钟 = 分钟) {
  cs.lastAdvanceMinutes = 本轮分钟;
  applyToolCall(cs, {
    name: 'bsUpdateCharacterStatus',
    arguments: { female: '她', options: { libidoClass: 档, libidoMinutes: 分钟 } },
  });
  return 取通知(cs);
}

// 停手：报 0 档，但时间照走
function 停(cs, 分钟) {
  cs.lastAdvanceMinutes = 分钟;
  applyToolCall(cs, {
    name: 'bsUpdateCharacterStatus',
    arguments: { female: '她', options: { libidoClass: 0, libidoMinutes: 0 } },
  });
  return 取通知(cs);
}

function 取通知(cs) {
  const t = String(p(cs).notify?.thirdly || '');
  const m = t.match(/去了一次（(.)）/g);
  return m ? m[m.length - 1] : '';
}

const 档名 = ['无', '想象', '环境', '轻', '中', '重'];

// 一行状态：她读出来是什么样
function 状态(cs) {
  const v = getLibidoView(p(cs));
  return `${v.text.padEnd(14)}`;
}

function 标题(n, s) {
  console.log(`\n${'─'.repeat(72)}\n【场景 ${n}】${s}\n${'─'.repeat(72)}`);
}

